@torch.no_grad()
def manual_attn_weights_firstn(q_inst: torch.Tensor,
                               k_img: torch.Tensor,
                               num_heads: int,
                               n_tokens: int | None = None,
                               chunk_k: int | None = None,
                               upcast: bool = True) -> torch.Tensor:
    """
    从 q_inst, k_img 手动计算 cross-attention 的 softmax 权重（不需要 v）。
    兼容你的shape：q_inst=[B,L_q,H*d], k_img=[B,L_k,H*d]
    返回:
        attn_map: [B, H, n, L_k]  （n = n_tokens 或 L_q）
    参数:
        num_heads: 你的 head 数 H
        n_tokens : 只取前 n 个 query token；None 表示用全部 L_q
        chunk_k  : 如果 L_k 很大，可按列分块（如 1024/2048）；None 表示不分块
        upcast   : 计算时上浮到 fp32 提升稳定性，然后回落到输入 dtype
    """
    assert q_inst.shape[-1] == k_img.shape[-1], "q/k 最后一维不一致"
    B, L_q, D = q_inst.shape
    _, L_k, Dk = k_img.shape
    assert D % num_heads == 0, "D 必须能被 num_heads 整除"
    d_head = D // num_heads
    n = L_q if n_tokens is None else min(n_tokens, L_q)

    # 选前 n 个 query
    q = q_inst[:, :n, :]            # [B, n, H*d]
    k = k_img                       # [B, L_k, H*d]

    # [B,H,L, d]
    q_h = rearrange(q, "b L (h d) -> b h L d", h=num_heads, d=d_head).contiguous()
    k_h = rearrange(k, "b L (h d) -> b h L d", h=num_heads, d=d_head).contiguous()

    # 上浮精度（更稳）
    comp_dtype = torch.float32 if upcast else q_h.dtype
    qh = q_h.to(comp_dtype)
    kh = k_h.to(comp_dtype)
    scale = 1.0 / math.sqrt(d_head)

    # 不分块：一次性算 scores→softmax
    if chunk_k is None or chunk_k >= L_k:
        scores = torch.matmul(qh, kh.transpose(-2, -1)) * scale      # [B,H,n,L_k]
        attn = torch.softmax(scores, dim=-1)
        return attn.to(q_inst.dtype)

    # 分块：两遍 log-sum-exp（稳定/省显存）
    B_, H_, n_ = B, num_heads, n
    device = q_inst.device
    m = torch.full((B_, H_, n_), -float("inf"), dtype=comp_dtype, device=device)  # 行最大
    z = torch.zeros((B_, H_, n_), dtype=comp_dtype, device=device)                # 行 exp 和
    for start in range(0, L_k, chunk_k):
        end = min(start + chunk_k, L_k)
        ks  = kh[:, :, start:end, :]                              # [B,H,ck,d]
        sc  = torch.matmul(qh, ks.transpose(-2, -1)) * scale      # [B,H,n,ck]
        m_new = torch.maximum(m, sc.amax(dim=-1))                 # [B,H,n]
        z = torch.exp(m - m_new) * z + torch.exp(sc - m_new.unsqueeze(-1)).sum(dim=-1)
        m = m_new

    attn = torch.empty((B_, H_, n_, L_k), dtype=comp_dtype, device=device)
    for start in range(0, L_k, chunk_k):
        end = min(start + chunk_k, L_k)
        ks  = kh[:, :, start:end, :]
        sc  = torch.matmul(qh, ks.transpose(-2, -1)) * scale      # [B,H,n,ck]
        attn_chunk = torch.exp(sc - m.unsqueeze(-1)) / z.unsqueeze(-1)  # 归一化
        attn[:, :, :, start:end] = attn_chunk

    return attn.to(q_inst.dtype)

class CrossAttention(nn.Module):
    def __init__(self, dim: int, num_heads: int, eps: float = 1e-6, has_image_input: bool = False):
        super().__init__()
        self.dim = dim
        self.num_heads = num_heads
        self.head_dim = dim // num_heads

        self.q = nn.Linear(dim, dim)
        self.k = nn.Linear(dim, dim)
        self.v = nn.Linear(dim, dim)
        self.o = nn.Linear(dim, dim)
        self.norm_q = RMSNorm(dim, eps=eps)
        self.norm_k = RMSNorm(dim, eps=eps)
        self.has_image_input = has_image_input
        if has_image_input:
            self.k_img = nn.Linear(dim, dim)
            self.v_img = nn.Linear(dim, dim)
            self.norm_k_img = RMSNorm(dim, eps=eps)
            
        self.attn = AttentionModule(self.num_heads)
        self._attn_map_hooks: List[Callable[[torch.Tensor], None]] = []

    def register_attn_map_hook(self, fn: Callable[[torch.Tensor], None]):
        self._attn_map_hooks.append(fn)

        class HookHandle:
            def __init__(self, hooks: list, ref: Callable):
                self.hooks = hooks
                self.ref = ref
            def remove(self):
                if self.ref in self.hooks:
                    self.hooks.remove(self.ref)

        return HookHandle(self._attn_map_hooks, fn)
        
    def forward(self, x: torch.Tensor, y: torch.Tensor, insts: torch.Tensor=None, seq_lens=None, insts_token_positions=None):
        if self.has_image_input:
            img = y[:, :257]
            ctx = y[:, 257:]
        else:
            ctx = y

        text_seq_length = ctx.shape[1]
        # print("x.shape: ", x.shape)
        # print("y.shape: ", y.shape)
        q = self.norm_q(self.q(x))
        k = self.norm_k(self.k(ctx))
        v = self.v(ctx)
        x = self.attn(q, k, v)

        # print("insts_token_positions: ", insts_token_positions)
        if self._attn_map_hooks and (insts is not None or insts_token_positions is not None) and seq_lens is not None:
            inst_attnmaps = []
            
            if insts_token_positions is not None:
                q_inst = rearrange(q, "b s (n d) -> b n s d", n=self.num_heads)
                k_inst = rearrange(k, "b s (n d) -> b n s d", n=self.num_heads)
                # Handle token positions case
                for i in range(len(seq_lens)):
                    positions = insts_token_positions[i]
                    if len(positions) > 0:
                        with torch.no_grad():
                            partial_identity = torch.zeros_like(k_inst, device=k_inst.device, dtype=k_inst.dtype)
                            row_indices = torch.tensor(positions)
                            len_row_indices = len(row_indices)
                            col_indices = torch.arange(len_row_indices)
                            indices = torch.stack([row_indices, col_indices])
                            identity = torch.sparse_coo_tensor(indices, torch.ones(len_row_indices), (text_seq_length, len_row_indices)).to_dense().to(v.device, v.dtype)
                            partial_identity[..., :text_seq_length, :len_row_indices] = identity
                        attn_weight = flash_attention_bsnd(q_inst, k_inst, partial_identity)[..., :len_row_indices]
                        attn_weight = attn_weight.mean(dim=1) # attn_weight.shape = (b, s, len_row_indices)
                        inst_attnmaps.append(attn_weight)
                        del partial_identity, identity, attn_weight, row_indices, col_indices, indices, len_row_indices
                del q_inst, k_inst
            else:

                len_inst = insts.shape[1]
                for i in range(len(seq_lens)):
                    inst = insts[i].unsqueeze(0)
                    # print("inst.shape: ", inst.shape)
                    k_inst = self.norm_k(self.k(inst))
                    v_inst = self.v(inst)
                    partial_identity = v_inst.clone()
                    partial_identity.zero_()
                    identity = torch.eye(len_inst, seq_lens[i], device=inst.device, dtype=inst.dtype)
                    partial_identity[..., :len_inst, :seq_lens[i]] = identity
                    inst_attn = self.attn(q, k_inst, partial_identity)[..., :seq_lens[i]]
                    inst_attnmaps.append(inst_attn)

            L_max = max(seq_lens)
            padded = []
            for attn_map, L in zip(inst_attnmaps, seq_lens):
                padded_map = F.pad(attn_map, (0, L_max - L), value=0.0)  # [B, S, L_max]
                padded.append(padded_map)
            inst_attn_tensor = torch.stack(padded, dim=1).contiguous()
            for fn in self._attn_map_hooks:
                fn(inst_attn_tensor)

        if self.has_image_input:
            k_img = self.norm_k_img(self.k_img(img))
            v_img = self.v_img(img)
            y = flash_attention(q, k_img, v_img, num_heads=self.num_heads)
            x = x + y
        return self.o(x)

class GateModule(nn.Module):
    def __init__(self,):
        super().__init__()

    def forward(self, x, gate, residual):
        return x + gate * residual

class DiTBlock(nn.Module):
    def __init__(self, has_image_input: bool, dim: int, num_heads: int, ffn_dim: int, eps: float = 1e-6):
        super().__init__()
        self.dim = dim
        self.num_heads = num_heads
        self.ffn_dim = ffn_dim

        self.self_attn = SelfAttention(dim, num_heads, eps)
        self.cross_attn = CrossAttention(
            dim, num_heads, eps, has_image_input=has_image_input)
        self.norm1 = nn.LayerNorm(dim, eps=eps, elementwise_affine=False)
        self.norm2 = nn.LayerNorm(dim, eps=eps, elementwise_affine=False)
        self.norm3 = nn.LayerNorm(dim, eps=eps)
        self.ffn = nn.Sequential(nn.Linear(dim, ffn_dim), nn.GELU(
            approximate='tanh'), nn.Linear(ffn_dim, dim))
        self.modulation = nn.Parameter(torch.randn(1, 6, dim) / dim**0.5)
        self.gate = GateModule()

    def forward(self, x, context, t_mod, freqs, insts=None, seq_lens=None, insts_token_positions=None):
        dtype = x.dtype
        # msa: multi-head self-attention  mlp: multi-layer perceptron
        shift_msa, scale_msa, gate_msa, shift_mlp, scale_mlp, gate_mlp = (
            self.modulation.to(dtype=t_mod.dtype, device=t_mod.device) + t_mod).chunk(6, dim=1)
        input_x = modulate(self.norm1(x), shift_msa, scale_msa)
        x = self.gate(x, gate_msa, self.self_attn(input_x, freqs))
        x = x + self.cross_attn(self.norm3(x), context, insts, seq_lens=seq_lens, insts_token_positions=insts_token_positions)
        input_x = modulate(self.norm2(x), shift_mlp, scale_mlp)
        x = self.gate(x, gate_mlp, self.ffn(input_x))
        return x

class MLP(torch.nn.Module):
    def __init__(self, in_dim, out_dim, has_pos_emb=False):
        super().__init__()
        self.proj = torch.nn.Sequential(
            nn.LayerNorm(in_dim),
            nn.Linear(in_dim, in_dim),
            nn.GELU(),
            nn.Linear(in_dim, out_dim),
            nn.LayerNorm(out_dim)
        )
        self.has_pos_emb = has_pos_emb
        if has_pos_emb:
            self.emb_pos = torch.nn.Parameter(torch.zeros((1, 514, 1280)))

    def forward(self, x):
        if self.has_pos_emb:
            x = x + self.emb_pos.to(dtype=x.dtype, device=x.device)
        return self.proj(x)

class Head(nn.Module):
    def __init__(self, dim: int, out_dim: int, patch_size: Tuple[int, int, int], eps: float):
        super().__init__()
        self.dim = dim
        self.patch_size = patch_size
        self.norm = nn.LayerNorm(dim, eps=eps, elementwise_affine=False)
        self.head = nn.Linear(dim, out_dim * math.prod(patch_size))
        self.modulation = nn.Parameter(torch.randn(1, 2, dim) / dim**0.5)

    def forward(self, x, t_mod):
        shift, scale = (self.modulation.to(dtype=t_mod.dtype, device=t_mod.device) + t_mod).chunk(2, dim=1)
        x = (self.head(self.norm(x) * (1 + scale) + shift))
        return x


class WanModel(torch.nn.Module):
    def __init__(
        self,
        dim: int,
        in_dim: int,
        ffn_dim: int,
        out_dim: int,
        text_dim: int,
        freq_dim: int,
        eps: float,
        patch_size: Tuple[int, int, int],
        num_heads: int,
        num_layers: int,
        has_image_input: bool,
        has_image_pos_emb: bool = False,
        has_ref_conv: bool = False,
        add_control_adapter: bool = False,
        in_dim_control_adapter: int = 24,
    ):
        super().__init__()
        self.dim = dim
        self.freq_dim = freq_dim
        self.has_image_input = has_image_input
        self.patch_size = patch_size

        self.patch_embedding = nn.Conv3d(
            in_dim, dim, kernel_size=patch_size, stride=patch_size)
        self.text_embedding = nn.Sequential(
            nn.Linear(text_dim, dim),
            nn.GELU(approximate='tanh'),
            nn.Linear(dim, dim)
        )
        self.time_embedding = nn.Sequential(
            nn.Linear(freq_dim, dim),
            nn.SiLU(),
            nn.Linear(dim, dim)
        )
        self.time_projection = nn.Sequential(
            nn.SiLU(), nn.Linear(dim, dim * 6))
        self.blocks = nn.ModuleList([
            DiTBlock(has_image_input, dim, num_heads, ffn_dim, eps)
            for _ in range(num_layers)
        ])
        self.head = Head(dim, out_dim, patch_size, eps)
        head_dim = dim // num_heads
        self.freqs = precompute_freqs_cis_3d(head_dim)

        if has_image_input:
            self.img_emb = MLP(1280, dim, has_pos_emb=has_image_pos_emb)  # clip_feature_dim = 1280
        if has_ref_conv:
            self.ref_conv = nn.Conv2d(16, dim, kernel_size=(2, 2), stride=(2, 2))
        self.has_image_pos_emb = has_image_pos_emb
        self.has_ref_conv = has_ref_conv
        if add_control_adapter:
            self.control_adapter = SimpleAdapter(in_dim_control_adapter, dim, kernel_size=patch_size[1:], stride=patch_size[1:])
        else:
            self.control_adapter = None

    def patchify(self, x: torch.Tensor,control_camera_latents_input: torch.Tensor = None):
        x = self.patch_embedding(x)
        # if self.control_adapter is not None and control_camera_latents_input is not None:
        #     y_camera = self.control_adapter(control_camera_latents_input)
        #     x = [u + v for u, v in zip(x, y_camera)]
        #     x = x[0].unsqueeze(0)
        grid_size = x.shape[2:]
        x = rearrange(x, 'b c f h w -> b (f h w) c').contiguous()
        return x, grid_size  # x, grid_size: (f, h, w)

    def unpatchify(self, x: torch.Tensor, grid_size: torch.Tensor):
        return rearrange(
            x, 'b (f h w) (x y z c) -> b c (f x) (h y) (w z)',
            f=grid_size[0], h=grid_size[1], w=grid_size[2], 
            x=self.patch_size[0], y=self.patch_size[1], z=self.patch_size[2]
        )

    def forward(self,
                x: torch.Tensor,
                timestep: torch.Tensor,
                context: torch.Tensor,
                clip_feature: Optional[torch.Tensor] = None,
                y: Optional[torch.Tensor] = None,
                use_gradient_checkpointing: bool = False,
                use_gradient_checkpointing_offload: bool = False,
                **kwargs,
                ):
        t = self.time_embedding(
            sinusoidal_embedding_1d(self.freq_dim, timestep))
        t_mod = self.time_projection(t).unflatten(1, (6, self.dim))
        context = self.text_embedding(context)
        
        if self.has_image_input:
            x = torch.cat([x, y], dim=1)  # (b, c_x + c_y, f, h, w)
            clip_embdding = self.img_emb(clip_feature)
            context = torch.cat([clip_embdding, context], dim=1)
        
        x, (f, h, w) = self.patchify(x)
        
        freqs = torch.cat([
            self.freqs[0][:f].view(f, 1, 1, -1).expand(f, h, w, -1),
            self.freqs[1][:h].view(1, h, 1, -1).expand(f, h, w, -1),
            self.freqs[2][:w].view(1, 1, w, -1).expand(f, h, w, -1)
        ], dim=-1).reshape(f * h * w, 1, -1).to(x.device)
        
        def create_custom_forward(module):
            def custom_forward(*inputs):
                return module(*inputs)
            return custom_forward

        for block in self.blocks:
            if self.training and use_gradient_checkpointing:
                if use_gradient_checkpointing_offload:
                    with torch.autograd.graph.save_on_cpu():
                        x = torch.utils.checkpoint.checkpoint(
                            create_custom_forward(block),
                            x, context, t_mod, freqs,
                            use_reentrant=False,
                        )
                else:
                    x = torch.utils.checkpoint.checkpoint(
                        create_custom_forward(block),
                        x, context, t_mod, freqs,
                        use_reentrant=False,
                    )
            else:
                x = block(x, context, t_mod, freqs)

        x = self.head(x, t)
        x = self.unpatchify(x, (f, h, w))
        return x

